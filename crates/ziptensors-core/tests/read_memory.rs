//! File: tests/read_memory.rs
//! Purpose: asserts the reader's memory bound of spec section 9.2 with a counting allocator.
//!
//! Main responsibilities: read a 256 MiB synthetic member, a field-split `Q8_0` member and members
//! over a delta blob in the ways that use the most memory, and compare the peak of live Rust
//! allocations with 3 × threads × chunk, or (4 × threads + 1) × chunk for reads of delta blobs, which
//! run in a container of their own so that the base scratch they leave behind is not charged to the
//! others.
//!
//! Key structures: `Counting`, the global allocator of this test binary.
//!
//! Implementation notes: a binary of its own, because a global allocator counts the whole process and
//! other tests would disturb it; it holds one test for the same reason. Allocations made inside zstd's
//! C code bypass this allocator: a decompression context is about 100 KiB per scratch entry, constant,
//! and a one-pass decode allocates no window. Data repeats a few chunks of generated bytes, which still
//! makes every chunk a real stored chunk at its own file offset.
//!
//! The `use` of the crate's modules below is what the `crate::` paths of `testkit.rs` resolve through.

use std::alloc::{GlobalAlloc, Layout, System};
use std::sync::Arc;
use std::sync::atomic::{AtomicUsize, Ordering};

use ziptensors_core::{chain, codec, error, format, io, types};

#[allow(dead_code, reason = "this test uses a part of the kit the unit tests share")]
#[path = "../src/read/testkit.rs"]
mod testkit;

use chain::{ElementWidth, FieldTable, RawStep, Step, View};
use codec::StreamPolicy;
use testkit::{ContainerBuilder, ExtentSpec, MemorySource, Rng, delta, identity, planes, tensor_like};
use ziptensors_core::{Chain, Container, Member, OpenOptions};

/// Counts live bytes and their peak, passing everything to the system allocator.
struct Counting;

static LIVE: AtomicUsize = AtomicUsize::new(0);
static PEAK: AtomicUsize = AtomicUsize::new(0);

fn grew(by: usize) {
    let live = LIVE.fetch_add(by, Ordering::Relaxed) + by;
    PEAK.fetch_max(live, Ordering::Relaxed);
}

fn shrank(by: usize) {
    LIVE.fetch_sub(by, Ordering::Relaxed);
}

// SAFETY: every call forwards to `System` with its arguments unchanged, and the counters neither
// allocate nor touch the memory.
unsafe impl GlobalAlloc for Counting {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        // SAFETY: the caller's contract is forwarded.
        let pointer = unsafe { System.alloc(layout) };
        if !pointer.is_null() {
            grew(layout.size());
        }
        pointer
    }

    unsafe fn alloc_zeroed(&self, layout: Layout) -> *mut u8 {
        // SAFETY: the caller's contract is forwarded.
        let pointer = unsafe { System.alloc_zeroed(layout) };
        if !pointer.is_null() {
            grew(layout.size());
        }
        pointer
    }

    unsafe fn dealloc(&self, pointer: *mut u8, layout: Layout) {
        // SAFETY: the caller's contract is forwarded.
        unsafe { System.dealloc(pointer, layout) };
        shrank(layout.size());
    }

    unsafe fn realloc(&self, pointer: *mut u8, layout: Layout, new_size: usize) -> *mut u8 {
        // Counted as a move, the worst an allocator may do: both blocks live at the moment of the
        // copy. A bound proven under this also holds for a realloc that works in place.
        grew(new_size);
        // SAFETY: the caller's contract is forwarded.
        let pointer = unsafe { System.realloc(pointer, layout, new_size) };
        if pointer.is_null() {
            shrank(new_size);
        } else {
            shrank(layout.size());
        }
        pointer
    }
}

#[global_allocator]
static ALLOCATOR: Counting = Counting;

const CHUNK: usize = 1 << 20;
const MEMBER_LEN: usize = 256 << 20;
/// Chunks of [`mixed_blob`].
const MIXED_CHUNKS: usize = 64;
/// `chunk_size` of the `Q8_0` blob: 1 MiB rounded down to whole 34-byte blocks, as the writer does.
const Q8_CHUNK: usize = (CHUNK / 34) * 34;
/// Chunks of the `Q8_0` blob.
const Q8_CHUNKS: usize = 32;
/// Length of the delta blob: the first 64 MiB of the plain member's blob.
const DELTA_LEN: usize = 64 << 20;
/// Thread counts measured; 12 is the machine of the acceptance benchmark, where the margin was least.
const THREADS: [usize; 4] = [1, 2, 4, 12];
/// What the bound leaves to fixed-size bookkeeping: plan records, thread pool state. It does not grow
/// with the chunk size or with the member.
const FIXED_SLACK: usize = 128 << 10;

/// Runs `read` and returns the peak of live bytes above `base`. The scratch a read leaves behind
/// counts: it is what the next read starts from.
fn peak_of(base: usize, read: impl FnOnce()) -> usize {
    PEAK.store(LIVE.load(Ordering::Relaxed), Ordering::Relaxed);
    read();
    PEAK.load(Ordering::Relaxed).saturating_sub(base)
}

/// The chunk that costs the most: every stream compressed, by little, so stored bytes and scratch are
/// both close to a whole chunk.
fn costly_chunk(seed: u64) -> Vec<u8> {
    tensor_like(seed, CHUNK, CHUNK).iter().map(|byte| byte & 0x7F).collect()
}

/// [`costly_chunk`] with noise in one plane, which then stays stored: three compressed streams.
fn three_plane_chunk(seed: u64) -> Vec<u8> {
    let mut chunk = costly_chunk(seed);
    let noise = tensor_like(seed + 16, CHUNK, CHUNK);
    for at in (3..CHUNK).step_by(4) {
        chunk[at] = noise[at];
    }
    chunk
}

/// 64 MiB of chunks with 3 compressed streams, then chunks with 3 and 4 in turn. Codec scratch grows
/// from three quarters of a chunk to a whole one, the step that once overshot the bound.
fn mixed_blob() -> Vec<u8> {
    let (three, four) = (three_plane_chunk(32), costly_chunk(33));
    (0..MIXED_CHUNKS)
        .flat_map(|at| if at < MIXED_CHUNKS / 2 || at % 2 == 0 { &three } else { &four })
        .copied()
        .collect()
}

/// `Q8_0` blocks whose three field streams all compress by little: the scratch path with codec scratch
/// close to a whole chunk.
fn q8_blob() -> Vec<u8> {
    let template = costly_chunk(40);
    (0..Q8_CHUNKS).flat_map(|_| template[..Q8_CHUNK].iter().copied()).collect()
}

/// The target of the delta blob: the plain blob's bytes XOR [`costly_chunk`], so that the residual of
/// every chunk takes the scratch path with all streams compressed by little.
fn delta_target(base: &[u8]) -> Vec<u8> {
    let residual = costly_chunk(50);
    base[..DELTA_LEN].iter().zip(residual.iter().cycle()).map(|(base, delta)| base ^ delta).collect()
}

/// A 256 MiB member of `planes(4)` chunks that take the scratch path, a member that widens 64 MiB of
/// the same blob, which also keeps a canonical chunk in scratch while it decodes, a widened member
/// over [`mixed_blob`], a field-split `Q8_0` member, and two members over a delta blob of the first
/// blob: one whole, whose chunks decode into the destination, one widened.
fn build() -> Vec<u8> {
    let templates: Vec<Vec<u8>> = (0..4).map(costly_chunk).collect();
    let canonical: Vec<u8> =
        (0..MEMBER_LEN / CHUNK).flat_map(|at| templates[at % 4].iter().copied()).collect();
    let mut builder = ContainerBuilder::new();
    let chain = planes(ElementWidth::Four);
    let policy = StreamPolicy::Entropy;
    let blob = builder.add_blob(canonical, chain, CHUNK as u32, policy);
    let wide = ExtentSpec {
        blob,
        blob_offset: 2,
        virt_len: (64 << 20) * 2,
        view: View::F16ToF32,
    };
    let reference = builder.add_member("plain", &[identity(blob, 0, MEMBER_LEN as u64)]);
    assert_eq!(reference.len(), MEMBER_LEN);
    let target = delta_target(&reference);
    drop(reference);
    builder.add_member("wide", &[wide]);
    let mixed = builder.add_blob(mixed_blob(), chain, CHUNK as u32, policy);
    let virt_len = (MIXED_CHUNKS * CHUNK * 2) as u64;
    let extent = ExtentSpec { blob: mixed, blob_offset: 0, virt_len, view: View::F16ToF32 };
    builder.add_member("mixed", &[extent]);
    let q8_chain = Chain::new(&[Step::Layout(chain::Layout::Fields(FieldTable::Q80))]).expect("valid");
    let q8 = builder.add_blob(q8_blob(), q8_chain, Q8_CHUNK as u32, policy);
    builder.add_member("q8", &[identity(q8, 0, (Q8_CHUNKS * Q8_CHUNK) as u64)]);
    let delta_chain = delta(ElementWidth::Four, chain);
    let tuned = builder.add_delta_blob(target, blob, 0, delta_chain, policy);
    builder.add_member("delta", &[identity(tuned, 0, DELTA_LEN as u64)]);
    let wide = ExtentSpec { blob: tuned, blob_offset: 2, virt_len: (32 << 20) * 2, view: View::F16ToF32 };
    builder.add_member("delta-wide", &[wide]);
    builder.finish()
}

/// Opens the container with `threads` threads.
fn open(file: Arc<MemorySource>, threads: usize) -> Container {
    let source: Arc<dyn io::RandomAccess> = file;
    let options = OpenOptions { threads, ..OpenOptions::default() };
    Container::from_source(source, &options).expect("a valid container opens")
}

/// The largest peak over the reads of plain blobs that stress each part of the bound, with `threads`
/// threads.
fn worst_peak(file: Arc<MemorySource>, threads: usize) -> usize {
    let container = open(file, threads);
    let plain = container.member("plain").expect("present");
    let wide = container.member("wide").expect("present");
    let mixed = container.member("mixed").expect("present");
    let q8 = container.member("q8").expect("present");
    let mut dst = vec![0; MEMBER_LEN];
    let base = LIVE.load(Ordering::Relaxed);

    // First, while scratch is empty, so that growing it is what gets measured.
    let growing = peak_of(base, || mixed.read_at(0, &mut dst[..128 << 20]).expect("reads"));
    let whole = peak_of(base, || plain.read_at(0, &mut dst).expect("reads"));
    let unaligned = peak_of(base, || plain.read_at(7, &mut dst[..MEMBER_LEN - 7]).expect("reads"));
    let random = peak_of(base, || random_reads(&plain, &mut dst));
    let widened = peak_of(base, || wide.read_at(1, &mut dst[..(128 << 20) - 1]).expect("reads"));
    let q8_len = Q8_CHUNKS * Q8_CHUNK;
    let fields = peak_of(base, || q8.read_at(5, &mut dst[..q8_len - 5]).expect("reads"));
    let fields_random = peak_of(base, || random_reads(&q8, &mut dst));
    eprintln!(
        "threads {threads}: growing {growing} whole {whole} unaligned {unaligned} random {random} \
         wide {widened} q8 {fields} q8 random {fields_random}"
    );
    growing.max(whole).max(unaligned).max(random).max(widened).max(fields).max(fields_random)
}

/// The largest peak over reads of delta blobs, in a container of its own, with `threads` threads.
fn worst_delta_peak(file: Arc<MemorySource>, threads: usize) -> usize {
    let container = open(file, threads);
    let tuned = container.member("delta").expect("present");
    let wide = container.member("delta-wide").expect("present");
    let mut dst = vec![0; 64 << 20];
    let base = LIVE.load(Ordering::Relaxed);

    let widened = peak_of(base, || wide.read_at(3, &mut dst[..(64 << 20) - 3]).expect("reads"));
    let whole = peak_of(base, || tuned.read_at(0, &mut dst).expect("reads"));
    let random = peak_of(base, || random_reads(&tuned, &mut dst));
    eprintln!("threads {threads}: delta wide {widened} whole {whole} random {random}");
    widened.max(whole).max(random)
}

/// Partial reads at seeded offsets, each the worst case for scratch: a full decode, then a copy.
fn random_reads(member: &Member, dst: &mut [u8]) {
    let mut rng = Rng(0x5EED);
    for _ in 0..64 {
        let offset = rng.below(member.len() - CHUNK as u64);
        let len = 1 + rng.below(CHUNK as u64) as usize;
        member.read_at(offset, &mut dst[..len]).expect("reads");
    }
}

/// `Chain::from_raw` runs per blob at most, and must stay free of allocation on its way.
fn assert_chain_resolution_does_not_allocate() {
    let chain = planes(ElementWidth::Four);
    let raw: Vec<RawStep> = chain.steps().map(Step::to_raw).collect();
    let base = LIVE.load(Ordering::Relaxed);
    let peak = peak_of(base, || assert_eq!(Chain::from_raw(&raw).expect("valid"), chain));
    assert_eq!(peak, 0);
}

#[test]
fn reads_stay_within_three_batches_above_the_destination() {
    assert_chain_resolution_does_not_allocate();
    let source = Arc::new(MemorySource::silent(build()));
    for threads in THREADS {
        let peak = worst_peak(Arc::clone(&source), threads);
        let bound = 3 * threads * CHUNK + FIXED_SLACK;
        assert!(peak <= bound, "{peak} bytes above the destination, bound {bound}");
        let peak = worst_delta_peak(Arc::clone(&source), threads);
        let bound = (4 * threads + 1) * CHUNK + FIXED_SLACK;
        assert!(peak <= bound, "{peak} bytes above the destination for delta reads, bound {bound}");
    }
}
